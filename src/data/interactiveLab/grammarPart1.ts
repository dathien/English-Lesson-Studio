import type {
  GrammarComponentToken,
  GrammarSimulation,
  LabAssessmentQuestion,
} from '../../types/interactiveLab';
import type {HighSchoolGrade} from '../../types/lesson';

export function tok(
  text: string,
  role: GrammarComponentToken['role'],
  labelVi: string,
): GrammarComponentToken {
  return {text, role, labelVi};
}

export function gq(
  code: string,
  idx: number,
  grade: HighSchoolGrade,
  unitId: string,
  prompt: string,
  options: [string, string, string, string],
  correct: 'A' | 'B' | 'C' | 'D',
  explanationVi: string,
  learningOutcome: string,
): LabAssessmentQuestion {
  const labels = ['A', 'B', 'C', 'D'] as const;
  return {
    id: `${code.toLowerCase()}-q${idx}`,
    unitId,
    grade,
    skill: 'grammar',
    cognitiveLevel: idx <= 2 ? 'recognition' : idx <= 4 ? 'comprehension' : 'application',
    format: 'mcq',
    prompt,
    options: options.map((text, i) => ({label: labels[i], text})),
    correctAnswer: correct,
    explanationVi,
    learningOutcome,
    points: 0.25,
    sourceLabel: `Interactive Lab · Grammar ${code}`,
  };
}

