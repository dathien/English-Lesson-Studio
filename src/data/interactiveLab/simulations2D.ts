type RawObj = [
  id: string,
  labelEn: string,
  labelVi: string,
  ipa: string,
  descriptionVi: string,
  exampleEn: string,
  x: number,
  y: number,
  targetZoneId?: string,
  soundType?: InteractiveObject['soundType'],
  accentHex?: string,
];

type RawZone = [
  id: string,
  labelEn: string,
  labelVi: string,
  x: number,
  y: number,
  accentHex: string,
  descriptionVi?: string,
];

function objs(rows: RawObj[]): InteractiveObject[] {
  return rows.map(([id, labelEn, labelVi, ipa, descriptionVi, exampleEn, x, y, targetZoneId, soundType, accentHex]) => ({
    id,
    labelEn,
    labelVi,
    ipa,
    descriptionVi,
    exampleEn,
    x,
    y,
    targetZoneId,
    soundType: soundType ?? 'speech',
    accentHex,
  }));
}

function zones(rows: RawZone[]): InteractiveTargetZone[] {
  return rows.map(([id, labelEn, labelVi, x, y, accentHex, descriptionVi]) => ({
    id,
    labelEn,
    labelVi,
    x,
    y,
    accentHex,
    descriptionVi,
  }));
}

