type RawObj3D = [
  id: string,
  labelEn: string,
  labelVi: string,
  ipa: string,
  descriptionVi: string,
  exampleEn: string,
  pos3d: [number, number, number],
  soundType?: InteractiveObject['soundType'],
  accentHex?: string,
];

function objs3d(rows: RawObj3D[]): InteractiveObject[] {
  return rows.map(([id, labelEn, labelVi, ipa, descriptionVi, exampleEn, pos3d, soundType, accentHex], idx) => ({
    id,
    labelEn,
    labelVi,
    ipa,
    descriptionVi,
    exampleEn,
    x: 15 + ((idx * 17) % 70),
    y: 25 + ((idx * 19) % 50),
    pos3d,
    soundType: soundType ?? 'speech',
    accentHex,
  }));
}

